// The process-metric reports an operator delivers (`process-metrics`), each a real report with what describes the phone
// and its use randomized ONCE, here, so every run delivers the same report:
//
// - QUIET: the first daily payload of the SE2's recording (`ProcessMetrics@IOS_DEVICE_APP.rec` in
//   `test/contracts/recordings`, iOS 26.6.2, 2026-10-08) — empty exit data, two hang buckets under a second.
// - ENDED_ABNORMALLY: the report behind Bugsink's SNAPSYNC-61 (build 2369, 2026-10-12), the one crossing a phone has
//   sent: one foreground memory-limit exit and seven hangs of 280–949 ms. Without what the app added to it on its way
//   out (`crossing.reasons`, `ownFootprint.*`).
// - FROZE: ENDED_ABNORMALLY with its exit data removed and its last hang bucket moved to 1940–1949 ms.
//
// Randomized: the device model, OS build, region, build number and version, the period, and every usage and memory
// figure (scaled by 0.6–1.4); hang bucket counts (1–3). Kept: keys, units and formatting, and what the rule reads — the
// exit tally, every hang bucket's bounds, a suspended footprint under the ceiling. Cut by a seeded script; re-cut
// rather than hand-edit.

