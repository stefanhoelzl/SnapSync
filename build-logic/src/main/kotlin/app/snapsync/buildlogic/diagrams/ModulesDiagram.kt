package app.snapsync.buildlogic.diagrams

import org.gradle.api.DefaultTask
import org.gradle.api.Project
import org.gradle.api.artifacts.ProjectDependency
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.TaskAction

/**
 * `architecture/modules.md`: the module graph, from the Gradle project model — every `project(…)` dependency any
 * module's configurations declare, deduplicated, each module inside the subgraph of its top-level directory.
 *
 * Report-aggregation configurations (`kover*`) are NOT architectural dependencies: Kover's `kover` configuration merges
 * another module's coverage DATA and puts nothing on a classpath. Left in, the coverage-crediting edges render as
 * `:core:ports -> :adapter:generic:mock` — every one pointing the opposite way to the real dependency, in the diagram
 * that IS the record.
 *
 * Deterministic: code-point order, `\n`, UTF-8, no timestamp and no absolute path.
 */
object ModulesDiagram {
    /** The graph of [root]'s modules: every subproject with a build file (a container path has none), and its edges. */
    fun model(root: Project): Pair<List<String>, List<Pair<String, String>>> {
        val modules = root.subprojects.filter { it.buildFile.exists() }
        val edges = modules.flatMap { module ->
            module.configurations.filterNot { it.name.startsWith("kover") }.flatMap { configuration ->
                configuration.dependencies.withType(ProjectDependency::class.java).map { module.path to it.path }
            }
        }
        return modules.map { it.path }.sorted() to edges.filter { (from, to) -> from != to }.distinct().sorted()
    }

    fun render(modules: List<String>, edges: List<Pair<String, String>>): String = buildString {
        append(HEADER)
        append("```mermaid\nflowchart LR\n")
        modules.groupBy { it.split(':')[1] }.toSortedMap().forEach { (group, members) ->
            append("  subgraph $group\n")
            members.sorted().forEach { append("    ${id(it)}[\"$it\"]\n") }
            append("  end\n")
        }
        edges.sortedWith(compareBy({ it.first }, { it.second })).forEach { (from, to) ->
            append("  ${id(from)} --> ${id(to)}\n")
        }
        append("```\n")
    }

    private val HEADER = """
        |# Module dependency graph
        |
        |Generated by `./gradlew build` (`architectureModulesDiagram`) from the Gradle project model: every
        |`project(...)` dependency declared by any configuration of any module, deduplicated, each module in the
        |subgraph of its top-level directory. Report-aggregation configurations (`kover*`) are excluded: they merge
        |coverage data rather than putting classes on a classpath, so an edge through one is not an architectural
        |dependency and would render backwards here. Do not edit: the build rewrites this file, and CI fails while
        |the committed copy differs.
        |
        |
    """.trimMargin()

    private fun id(path: String): String = path.trimStart(':').replace(':', '_').replace('-', '_')

    private fun List<Pair<String, String>>.sorted() = sortedWith(compareBy({ it.first }, { it.second }))
}

/** Writes [ModulesDiagram] from the model read at configuration time — the task itself never touches a `Project`. */
abstract class ModulesDiagramTask : DefaultTask() {
    @get:Input
    abstract val modules: ListProperty<String>

    /** Each edge as `"<from> <to>"`. */
    @get:Input
    abstract val edges: ListProperty<String>

    @get:OutputFile
    abstract val diagram: RegularFileProperty

    @TaskAction
    fun render() {
        val edges = edges.get().map { it.substringBefore(' ') to it.substringAfter(' ') }
        Committed.write(diagram.get().asFile, ModulesDiagram.render(modules.get(), edges), logger)
    }
}
