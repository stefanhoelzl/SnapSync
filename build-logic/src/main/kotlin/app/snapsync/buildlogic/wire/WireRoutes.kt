package app.snapsync.buildlogic.wire

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeName
import com.squareup.kotlinpoet.TypeSpec
import com.squareup.kotlinpoet.asTypeName

/**
 * The app's half of the wire, written from a [WireDescription] (`docs/architecture.md`, "The backend boundary"):
 *
 * - `Replies.kt` — the sealed [Reply] hierarchy: the groups (`Success`, `ClientError`, `ServerIssue`, `NoAnswer`),
 *   each shared outcome ONCE, implementing every route reply that answers with it, and one sealed `<Op>Reply` per
 *   operation the app sends, its own outcomes nested in it;
 * - `Routes.kt` — one object per operation: its path builder, and for one the app sends, a request builder typed
 *   `GatedRequest` or `OpenRequest` by the operation's `security` (so only a gated request can carry a token) whose
 *   decoder turns an answer into that reply — an undeclared status, or a declared one that does not decode, is
 *   `Malformed`;
 * - `Limits.kt` — the constraints the app reads (`x-snapsync-export`), and the version gate's header.
 *
 * DTOs are not written here: Fabrikt writes them into [MODELS] (`snapsync.wire`); the hand-written runtime both call
 * is `app.snapsync.wire.runtime`.
 */
object WireRoutes {
    const val PACKAGE = "app.snapsync.wire.api"
    const val MODELS = "app.snapsync.wire.models"
    internal const val RUNTIME = "app.snapsync.wire.runtime"

    internal val REPLY = ClassName(PACKAGE, "Reply")
    internal val WIRE_REQUEST = ClassName(RUNTIME, "WireRequest")
    internal val WIRE_RESPONSE = ClassName(RUNTIME, "WireResponse")
    internal val GATED = ClassName(PACKAGE, "GatedRequest")
    internal val OPEN = ClassName(PACKAGE, "OpenRequest")
    internal val MALFORMED = ClassName(PACKAGE, "Malformed")
    internal val UNREACHABLE = ClassName(PACKAGE, "Unreachable")
    internal val GROUPS = listOf("Success", "ClientError", "ServerIssue", "NoAnswer")
    internal const val GENERATED =
        "GENERATED by build-logic's snapsync.wire from api/openapi.yaml — never edit, never commit."

    /** The generated files, by name. */
    fun generate(d: WireDescription): Map<String, String> = mapOf(
        "Replies.kt" to WireReplies.replies(d).toString(),
        "Routes.kt" to WireRouteObjects.routes(d).toString(),
        "Limits.kt" to limits(d).toString(),
    )

    internal fun replyName(op: WireOperation) = ClassName(PACKAGE, "${op.id.capitalized()}Reply")

    /** An outcome's constructor parameters: what its payload carries, then its declared headers. */
    internal fun fields(outcome: WireOutcome): List<Pair<String, TypeName>> {
        val body = when (val p = outcome.payload) {
            WirePayload.None -> null
            WirePayload.Text -> "text" to String::class.asTypeName()
            is WirePayload.Json -> p.schema.decapitalized() to ClassName(MODELS, p.schema)
            is WirePayload.JsonList -> "items" to List::class.asTypeName().parameterizedBy(ClassName(MODELS, p.schema))
        }
        val headers = outcome.headers.map { h ->
            h.name.identifier() to String::class.asTypeName().copy(nullable = !h.required)
        }
        return listOfNotNull(body) + headers
    }

    private fun limits(d: WireDescription): FileSpec {
        val limits = TypeSpec.objectBuilder("Limits").addKdoc("The constraints of `api/openapi.yaml` the app reads.")
        d.exports.forEach { (name, value) ->
            limits.addProperty(PropertySpec.builder(name, Int::class, KModifier.CONST).initializer("%L", value).build())
        }
        limits.addProperty(
            PropertySpec.builder("VERSION_HEADER", String::class, KModifier.CONST).initializer("%S", d.versionHeader)
                .addKdoc("The header every request declares the calling build's version in (the version gate).")
                .build(),
        )
        return FileSpec.builder(PACKAGE, "Limits").addFileComment(GENERATED).addType(limits.build()).build()
    }
}

/** The operations the app sends itself — not the OS-performed byte routes, not a preflight. */
internal val WireDescription.appOperations get() = operations.filter { !it.os && it.method != "OPTIONS" }

internal fun WireOperation.outcomes(): List<WireOutcome> = responses.values.flatMap { b ->
    when (b) {
        is WireBranch.Single -> listOf(b.outcome)
        is WireBranch.ByMedia -> b.outcomes.map { it.second }
        is WireBranch.ByText -> b.outcomes.map { it.second }
    }
}

internal val WireOperation.pathParameters get() = parameters.filter { it.location == "path" }
internal val WireOperation.queryParameters get() = parameters.filter { it.location == "query" }
internal val WireOperation.headerParameters get() = parameters.filter { it.location == "header" }

internal fun String.capitalized() = replaceFirstChar { it.uppercase() }
internal fun String.decapitalized() = replaceFirstChar { it.lowercase() }

/** A wire name (`SnapSync-Cursor`, `x-snapsync-file-key`, `eventId`) as a Kotlin identifier. */
internal fun String.identifier(): String {
    val parts = split('-', '_').filter { it.isNotEmpty() }
    return parts.first().replaceFirstChar { it.lowercase() } + parts.drop(1).joinToString("") {
        it.lowercase().replaceFirstChar { c -> c.uppercase() }
    }
}

/** A wire name as a constant's suffix (`x-snapsync-file-key` → `X_SNAPSYNC_FILE_KEY`). */
internal fun String.constant(): String = split('-', '_').joinToString("_") { it.uppercase() }
