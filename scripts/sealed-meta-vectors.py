#!/usr/bin/env -S uv run --quiet --with cryptography python
# Regenerates test/vectors/sealed-meta.json — the reference vectors both halves of an encrypted event's SEALED
# METADATA record are held to (`api/src/sealed-meta.ts`, `:domain:format`'s SealedMetaFormat and data's metadata
# cipher). Like `encrypted-file-vectors.py`, deliberately an implementation INDEPENDENT of both, over
# pyca/cryptography. Deterministic: the nonces are fixed here (a real seal draws a fresh random one), so re-running
# it rewrites the same file.
#
# The record (decision record `changes/seal-event-name`, D2/D3):
#   metaKey  = HKDF-SHA256(event key, salt = none, info = "snapsync/meta/v1"), 32 bytes
#   envelope = 0x01 ‖ nonce (12) ‖ AES-256-GCM ciphertext ‖ tag (16), unpadded base64url; GCM carries NO associated
#              data — the binding is the derivation's label, as the encrypted file format binds a file (D2)
#   plaintext: a UTF-8 JSON object, today {"name": "…"}; readers ignore keys they do not know.
#
# A photo's FILE NAME (decision record `changes/seal-file-names`, D1) is the same envelope and record, under a key
# derived per photo, so the service cannot move a name onto another photo:
#   fileNameKey = HKDF-SHA256(event key, salt = none,
#                             info = "snapsync/file-name/v1/<eventId>/<deviceId>/<assetId>/<role>"), 32 bytes
import base64, json
from pathlib import Path
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives import hashes

LABEL = b"snapsync/meta/v1"
VERSION = 1

def hkdf(ikm, salt, info, n):
    return HKDF(algorithm=hashes.SHA256(), length=n, salt=salt, info=info).derive(ikm)

def key_id(event_key):
    return hkdf(event_key, b"", b"snapsync/key-id/v1", 8)

def meta_key(event_key, label=LABEL):
    return hkdf(event_key, b"", label, 32)

def b64(raw):
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()

def seal(event_key, nonce, plaintext, label=LABEL):
    return bytes([VERSION]) + nonce + AESGCM(meta_key(event_key, label)).encrypt(nonce, plaintext, None)

event_key = bytes(range(32))
other_key = bytes([0xff]) * 32
nonce = bytes(range(0x10, 0x1c))

# Each plaintext is given as the exact UTF-8 text sealed, so a reader compares bytes, not a re-serialised object.
plaintexts = [
    '{"name":"Ana\'s 30th"}',
    '{"name":"Ski Trip","future":{"kept":true}}',
    '{"name":"' + "\U0001F389" * 100 + '"}',
]

vectors = {
    "about": "SnapSync sealed-metadata reference vectors (decision record changes/seal-event-name). metaKey = "
             "HKDF-SHA256(eventKey, no salt, 'snapsync/meta/v1'); envelope = 0x01 || nonce(12) || AES-256-GCM "
             "ciphertext || tag(16) with no associated data, unpadded base64url. Nonces are fixed for "
             "determinism only. fileName: a photo's name, the same envelope under HKDF-SHA256(eventKey, no "
             "salt, 'snapsync/file-name/v1/<eventId>/<deviceId>/<assetId>/<role>'). Generated by an implementation independent of the app (Python cryptography).",
    "metaKey": [],
    "seal": [],
    "reject": [],
}
for k in [event_key, bytes(32), other_key]:
    vectors["metaKey"].append({"eventKey": k.hex(), "keyId": key_id(k).hex(), "metaKey": meta_key(k).hex()})
for pt in plaintexts:
    vectors["seal"].append({"eventKey": event_key.hex(), "keyId": key_id(event_key).hex(), "nonce": nonce.hex(),
                            "plaintext": pt, "envelope": b64(seal(event_key, nonce, pt.encode()))})

good = seal(event_key, nonce, plaintexts[0].encode())
vectors["reject"] = [
    {"reason": "sealed under another event's key", "eventKey": event_key.hex(), "keyId": key_id(event_key).hex(),
     "envelope": b64(seal(other_key, nonce, plaintexts[0].encode()))},
    {"reason": "sealed under another label", "eventKey": event_key.hex(), "keyId": key_id(event_key).hex(),
     "envelope": b64(seal(event_key, nonce, plaintexts[0].encode(), label=b"snapsync/meta/v2"))},
    {"reason": "unknown version byte", "eventKey": event_key.hex(), "keyId": key_id(event_key).hex(),
     "envelope": b64(bytes([2]) + good[1:])},
    {"reason": "truncated tag", "eventKey": event_key.hex(), "keyId": key_id(event_key).hex(),
     "envelope": b64(good[:-1])},
    {"reason": "shorter than an empty record", "eventKey": event_key.hex(), "keyId": key_id(event_key).hex(),
     "envelope": b64(good[:28])},
    {"reason": "a flipped ciphertext byte", "eventKey": event_key.hex(), "keyId": key_id(event_key).hex(),
     "envelope": b64(good[:13] + bytes([good[13] ^ 1]) + good[14:])},
]

def file_name_label(b):
    return f"snapsync/file-name/v1/{b['eventId']}/{b['deviceId']}/{b['assetId']}/{b['role']}".encode()

binding = {"eventId": "0b5e1c2a-7d4f-4c1e-9a3b-2f6d8e0c1a5b", "deviceId": "6f1d2c3b-4a5e-4f60-8172-93a4b5c6d7e8",
           "assetId": "1234", "role": "primary"}
moved = dict(binding, assetId="1235")
file_names = ['{"name":"IMG_4471.HEIC"}', '{"name":"Lena\'s cake \U0001F382.jpg","future":1}']

vectors["fileName"] = []
for pt in file_names:
    vectors["fileName"].append({"eventKey": event_key.hex(), "binding": binding,
                                "fileNameKey": meta_key(event_key, file_name_label(binding)).hex(),
                                "nonce": nonce.hex(), "plaintext": pt,
                                "envelope": b64(seal(event_key, nonce, pt.encode(), label=file_name_label(binding)))})
vectors["fileNameReject"] = [
    {"reason": "sealed for another photo", "eventKey": event_key.hex(), "binding": binding,
     "envelope": b64(seal(event_key, nonce, file_names[0].encode(), label=file_name_label(moved)))},
    {"reason": "sealed as the event's record", "eventKey": event_key.hex(), "binding": binding,
     "envelope": b64(seal(event_key, nonce, file_names[0].encode()))},
    {"reason": "sealed under another event's key", "eventKey": event_key.hex(), "binding": binding,
     "envelope": b64(seal(other_key, nonce, file_names[0].encode(), label=file_name_label(binding)))},
    {"reason": "an empty name", "eventKey": event_key.hex(), "binding": binding,
     "envelope": b64(seal(event_key, nonce, b'{"name":""}', label=file_name_label(binding)))},
]

out = Path(__file__).resolve().parent.parent / "test/vectors/sealed-meta.json"
out.write_text(json.dumps(vectors, indent=1, ensure_ascii=False) + "\n")
print(len(vectors["seal"]), "seal vectors,", len(vectors["reject"]), "reject vectors,",
      len(vectors["fileName"]), "file-name vectors,", len(vectors["fileNameReject"]), "file-name reject vectors")
