/** One statement of a schema, run against its generated queries with fixed arguments. */
class SchemaStatement<Q>(val name: String, val run: (Q) -> Unit)

/** Every statement of one schema (generated by `generateSchemaStatements`): what reads it, and what writes it. */
interface SchemaStatements<Q> {
    val reads: List<SchemaStatement<Q>>
    val writes: List<SchemaStatement<Q>>
}

/**
 * A production schema as the clauses address it: its generated database over a driver, that database's queries,
 * and the oldest version a migration still ships from, with one row in it.
 */
private class ProductionSchema<D : Transacter, Q>(
    val label: String,
    val schema: SqlSchema<QueryResult.Value<Unit>>,
    val database: (SqlDriver) -> D,
    val queries: (D) -> Q,
    val statements: SchemaStatements<Q>,
    val firstVersion: Long,
    val firstRow: String,
)

// ---- a schema as it stood at an older version -------------------------------------------------------------------

/**
 * [this] schema as it stood at [version], holding [rows]: every migration below [version] run on an empty database.
 * The migration chain is each schema's only source (`deriveSchemaFromMigrations`), so an older shape is never written
 * out by hand — a copy would be a second source that could disagree with what devices hold. Shared with the services'
 * migration suites.
 */
fun SqlSchema<QueryResult.Value<Unit>>.at(version: Long, vararg rows: String): SqlSchema<QueryResult.Value<Unit>> {
    val current = this
    return object : SqlSchema<QueryResult.Value<Unit>> {
        override val version = version
        override fun create(driver: SqlDriver) = QueryResult.Value(
            current.migrate(driver, 0, version).value.also { rows.forEach { driver.execute(null, it, 0) } },
        )

        override fun migrate(driver: SqlDriver, oldVersion: Long, newVersion: Long, vararg callbacks: AfterVersion) =
            QueryResult.Value(Unit)
    }
}

/** The column encoding is the services' business; a statement needs only a value it can bind and read back. */
private class Text<T : Any>(
    private val wrap: (String) -> T,
    private val unwrap: (T) -> String,
) : ColumnAdapter<T, String> {
    override fun decode(databaseValue: String) = wrap(databaseValue)
    override fun encode(value: T) = unwrap(value)
}

private val AssetIdText = Text(::AssetId, AssetId::value)
private val EventIdText = Text({ requireNotNull(EventId.parse(it)) }, EventId::value)
private val DeviceIdText = Text({ requireNotNull(DeviceId.parse(it)) }, DeviceId::value)

/** A date role's column, as its whole-second instant's epoch text: any instant binds and reads back. */
private fun <T : Any> dateText(wrap: (Timestamp) -> T, unwrap: (T) -> Timestamp) =
    Text({ wrap(Timestamp.of(Instant.parse(it))) }, { unwrap(it).at.toString() })

