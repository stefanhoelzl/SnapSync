/** [production] at its oldest migrated-from version, as a schema the port can create: those tables, holding a row. */
private fun firstVersionOf(production: ProductionSchema<*, *>) =
    production.schema.at(production.firstVersion, production.firstRow)

private fun Databases.openedReadWrite(name: String, schema: SqlSchema<QueryResult.Value<Unit>>): SqlDriver {
    val opened = open(name, schema, readOnly = false)
    assertIs<DbOpen.Opened>(opened, "expected $name to open read-write, got $opened")
    return opened.driver
}

/**
 * Runs every statement of [production] on [driver]: each read on the database as it is, then each write in a
 * transaction that is rolled back — the reads run again inside it, so they also see a row the write left. A
 * failure names the statement: what failed is this platform's SQLite, not a service rule.
 */
private fun <D : Transacter, Q> runEveryStatement(production: ProductionSchema<D, Q>, driver: SqlDriver) {
    val database = production.database(driver)
    val queries = production.queries(database)
    fun SchemaStatement<Q>.runHere() = try {
        run(queries)
    } catch (e: Exception) {
        throw AssertionError("${production.label}.$name failed on this SQLite: ${e.message}", e)
    }
    production.statements.reads.forEach { it.runHere() }
    production.statements.writes.forEach { write ->
        database.transaction {
            write.runHere()
            production.statements.reads.forEach { it.runHere() }
            rollback()
        }
    }
}

/**
 * What a schema IS, independent of the order it was built in: its objects, each table's columns, each index's.
 * A column's DEFAULT is left out: `ADD COLUMN … NOT NULL` must carry one that the created table need not, and every
 * write names the column anyway.
 */
private fun SqlDriver.shape(): List<String> {
    val objects = rows("SELECT type, name, tbl_name FROM sqlite_master WHERE name NOT LIKE 'sqlite_%'", 3)
    val columns = objects.filter { it[0] == "table" }.flatMap { (_, table) ->
        rows("SELECT name, type, \"notnull\", pk FROM pragma_table_info('$table')", 4)
            .map { listOf("column", table) + it }
    }
    val indexed = objects.filter { it[0] == "index" }.flatMap { (_, index) ->
        rows("SELECT seqno, name FROM pragma_index_info('$index')", 2).map { listOf("indexed", index) + it }
    }
    return (objects + columns + indexed).map { it.joinToString(" ") }.sorted()
}

private fun SqlDriver.rows(sql: String, width: Int): List<List<String?>> =
    executeQuery(null, sql, { c ->
        QueryResult.Value(buildList { while (c.next().value) add((0 until width).map { c.getString(it) }) })
    }, 0).value

/**
 * The production schemas' clauses (`docs/testing.md`, "Every statement runs on every SQLite"): the services' rules
 * are tested over the mocks on the JVM, so these are what keep each platform's own SQLite executing every
 * statement of `ledger.db` and `downloads.db` — through the port, on a database the adapter created or migrated.
 *
 * They assert that a statement RUNS, never what it answers: that is the services' contract, not the platform's.
 */
internal fun ClauseList<DatabasesState, DatabasesSubject>.schemaClauses() {
    listOf(LEDGER, DOWNLOADS).forEach { production ->
        val prefix = production.label.uppercase()

        clause(
            "${prefix}_SCHEMA_EVERY_STATEMENT_RUNS",
            DatabasesState.ABSENT,
            covers = cells { on<Databases>().answers(Databases::open).with(DbOpen.Opened::class) },
        ) { (databases) ->
            val driver = databases.openedReadWrite("${production.label}.db", production.schema)
            runEveryStatement(production, driver)
            driver.close()
        }

        clause(
            "${prefix}_SCHEMA_MIGRATES_FROM_ITS_FIRST_VERSION",
            DatabasesState.ABSENT,
            covers = cells { on<Databases>().answers(Databases::open).with(DbOpen.Opened::class) },
        ) { (databases) ->
            databases.openedReadWrite("migrated.db", firstVersionOf(production)).close()
            val migrated = databases.openedReadWrite("migrated.db", production.schema)
            val created = databases.openedReadWrite("created.db", production.schema)
            assertEquals(
                created.shape(),
                migrated.shape(),
                "a migrated ${production.label} database is the created one",
            )
            created.close()
            runEveryStatement(production, migrated)
            migrated.close()
        }
    }
}
