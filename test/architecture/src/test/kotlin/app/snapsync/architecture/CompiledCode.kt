package app.snapsync.architecture

import java.io.File

/**
 * **What our compiled production code does, per target** (`docs/testing.md`, "Every adapter is covered"): the classes
 * one target links, each function reduced to the facts the per-adapter gate needs — which of our classes it builds,
 * which enum entries it reads, what it calls, which values reach it from code it cannot see, and what it returns.
 *
 * Read from what the compiler emitted, never from source: JVM and Android classes through ASM ([BytecodeReader]), the iOS
 * klibs through `klib dump-ir` ([IrReader]). Both readers produce this one shape, so [NeverAnswersCheck] judges every
 * platform by the same rules.
 */
internal enum class CodeTarget(val label: String) {
    JVM("jvm"),
    ANDROID("android"),
    IOS_ARM64("iosArm64"),
    IOS_SIMULATOR_ARM64("iosSimulatorArm64"),
}

/** A type as the compiled code states it: our classes by dotted FQN (`app.snapsync.ports.FileResult.Ok`). */
internal data class CodeType(val fqn: String, val nullable: Boolean) {
    override fun toString() = fqn + if (nullable) "?" else ""
}

/** A call from one function: [key] is the callee's function key, or `null` for an IR call named by owner and name only. */
internal data class CallRef(val key: String?, val owner: String?, val name: String, val type: CodeType?)

/** A value that enters a function from code the walk does not see, of [type], described by [origin]. */
internal data class Inflow(val type: CodeType, val origin: String)

/** A field, by its owner's FQN and its name. */
internal data class FieldRef(val owner: String, val name: String)

/** Where a cast's value came from — what decides whether the cast could turn an unseen value into the answer. */
internal sealed interface Source {
    /** A value of this static type (IR): only a type that cannot already be the answer hides where it came from. */
    data class Typed(val type: CodeType) : Source

    /** The result of a call: ours (walked) or not. */
    data class Call(val ref: CallRef) : Source

    /** A parameter of the function the bytecode method is (its key). */
    data class Param(val declaredIn: String) : Source

    data class Field(val field: FieldRef) : Source

    /** What a suspension resumed with: the answer of one of the suspend calls the function makes. */
    data object SuspendResult : Source

    /** Built or read as a constant here: an allocation, an `object`, an enum entry, a literal, a lambda. */
    data object Ours : Source

    /** Anything else (an array element, an unanalysable method): could be anything. */
    data class Unknown(val what: String) : Source
}

/** A cast to [type] of a value from [sources]. */
internal data class Cast(val type: CodeType, val sources: List<Source>)

/** What a function returns directly: a literal (`true`, `false`, `null`), a read of [field], or anything else. */
internal sealed interface Returned {
    data class Literal(val text: String) : Returned
    data class Field(val field: FieldRef) : Returned
    data object Other : Returned
}

internal class Facts(
    /** Our classes this code constructs, or whose `object` instance it reads. */
    val builds: Set<String> = emptySet(),
    /** Enum entries it reads, as `EnumFqn.ENTRY`. */
    val enumEntries: Set<String> = emptySet(),
    val calls: List<CallRef> = emptyList(),
    /** Values entering unseen, of a type the walk weighs against the answer. */
    val inflows: List<Inflow> = emptyList(),
    /** Every cast, with where its value came from. */
    val casts: List<Cast> = emptyList(),
    /** Parameters it reads: their type, and the function they are declared in (IR: `Owner.fun`; JVM: the method key). */
    val paramReads: List<Pair<CodeType, String>> = emptyList(),
    val fieldReads: List<Pair<FieldRef, CodeType>> = emptyList(),
    val fieldWrites: Set<FieldRef> = emptySet(),
    /** Functions it hands on as values (lambdas, references): reachable, and their parameters come from anyone. */
    val handsOn: Set<String> = emptySet(),
    val returns: List<Returned> = emptyList(),
)

internal class CodeFun(
    /** Unique within a target. */
    val key: String,
    val owner: String,
    val name: String,
    val returnType: CodeType?,
    /** Compiler-generated: `FAKE_OVERRIDE` (an inherited member, no body here) or a bridge. */
    val inherited: Boolean,
    /** A member generated by `by` delegation: its answer is the delegate's. */
    val delegated: Boolean,
    /** The keys of the members this one overrides, as the compiler records them (IR), or empty (JVM: derived). */
    val overrides: List<String>,
    val abstract: Boolean,
    val facts: Facts,
    /** Callable only from its own class: every value it is handed comes from code the class holds. */
    val private: Boolean = false,
)

internal class CodeClass(
    val fqn: String,
    val isInterface: Boolean,
    val isAbstract: Boolean,
    val isEnum: Boolean,
    val supertypes: List<String>,
    val funs: List<CodeFun>,
    /** Field initializers, as facts of the field they initialize. */
    val fieldInits: Map<String, Facts>,
    val fieldTypes: Map<String, CodeType>,
    /** `$$delegate_N` fields: the delegate's declared type. */
    val delegates: List<CodeType>,
    /** The class's `@NeverAnswers` claims, as written: (member, answer, handler), unset ones empty. */
    val claims: List<Triple<String, String, String>>,
    val origin: Origin = Origin(),
) {
    /** A local or anonymous class: whoever builds it may run any of its functions. */
    val local: Boolean get() = origin.local

    /** The source set it was compiled from (`iosMain`, `iosSimulatorArm64Main`, …), where the code says; empty if not. */
    val sourceSet: String get() = origin.sourceSet
}

/** Where a class comes from: whether it is local or anonymous, and the source set it was compiled from. */
internal class Origin(val local: Boolean = false, val sourceSet: String = "")

/** One target's code: every production class it links, indexed for the walks. */
internal class CodeBase(val target: CodeTarget, classes: List<CodeClass>) {
    val classes: Map<String, CodeClass> = classes.associateBy { it.fqn }
    val funs: Map<String, CodeFun> = classes.flatMap { it.funs }.associateBy { it.key }
    private val byOwnerName: Map<String, List<CodeFun>> = classes.flatMap { it.funs }.groupBy { "${it.owner}#${it.name}" }

    /** Every class's supertypes, transitively, within our code (names outside it are kept as leaves). */
    fun ancestors(fqn: String): Set<String> {
        val out = linkedSetOf<String>()
        val todo = ArrayDeque(listOf(fqn))
        while (todo.isNotEmpty()) {
            val next = todo.removeFirst()
            classes[next]?.supertypes?.forEach { if (out.add(it)) todo += it }
        }
        return out
    }

    private val subtypes: Map<String, Set<String>> by lazy {
        val out = mutableMapOf<String, MutableSet<String>>()
        this.classes.keys.forEach { c -> ancestors(c).forEach { a -> out.getOrPut(a) { mutableSetOf() } += c } }
        out
    }

    fun subtypesOf(fqn: String): Set<String> = subtypes[fqn].orEmpty()

    private val writers: Map<FieldRef, List<CodeFun>> by lazy {
        val out = mutableMapOf<FieldRef, MutableList<CodeFun>>()
        funs.values.forEach { f -> f.facts.fieldWrites.forEach { out.getOrPut(it) { mutableListOf() } += f } }
        out
    }

    /** Every function that writes [field]. */
    fun writersOf(field: FieldRef): List<CodeFun> = writers[field].orEmpty()

    /**
     * The functions a call to [ref] may run: the callee itself when it has a body, and every implementation in this
     * target's production code that overrides it — the conservative reading of a dispatch ("Unresolvable calls"). Empty
     * when the callee is not our code: the walk then bounds the call by its type.
     */
    fun targets(ref: CallRef): List<CodeFun> {
        val direct = ref.key?.let { funs[it] }
        val named = if (ref.key == null && ref.owner != null) byOwnerName["${ref.owner}#${ref.name}"].orEmpty() else emptyList()
        val roots = listOfNotNull(direct) + named
        if (roots.isEmpty()) {
            // A JVM call names the static receiver; the member may be declared further up, or only in implementations.
            val owner = ref.owner ?: return emptyList()
            return implementations(owner, ref.name, ref.key)
        }
        return (roots.filterNot { it.abstract || it.inherited } + roots.flatMap { overridersOf(it) }).distinctBy { it.key }
    }

    private fun implementations(owner: String, name: String, key: String?): List<CodeFun> {
        val descriptor = key?.substringAfter(' ', "")
        return (setOf(owner) + subtypesOf(owner)).mapNotNull { classes[it] }.flatMap { c ->
            c.funs.filter { f ->
                f.name == name && !f.abstract && !f.inherited && (descriptor.isNullOrEmpty() || f.key.endsWith(" $descriptor"))
            }
        }
    }

    private val overriders: Map<String, List<CodeFun>> by lazy {
        val out = mutableMapOf<String, MutableList<CodeFun>>()
        funs.values.forEach { f -> f.overrides.forEach { out.getOrPut(it) { mutableListOf() } += f } }
        out
    }

    /** Every function overriding [f], transitively, with a body. */
    private fun overridersOf(f: CodeFun): List<CodeFun> {
        val out = mutableListOf<CodeFun>()
        val todo = ArrayDeque(listOf(f.key))
        val seen = mutableSetOf<String>()
        while (todo.isNotEmpty()) {
            overriders[todo.removeFirst()].orEmpty().forEach { o ->
                if (seen.add(o.key)) {
                    if (!o.abstract && !o.inherited) out += o
                    todo += o.key
                }
            }
        }
        return out
    }

    companion object {
        /** The code bases the build handed this test run, one per target, read once per JVM. */
        val all: Map<CodeTarget, CodeBase> by lazy {
            CodeTarget.entries.associateWith { target ->
                val inputs = System.getProperty("snapsync.code.${target.label}")
                    ?: error(
                        "no compiled code for ${target.label}: `:test:architecture:test` hands it in as the system " +
                            "property snapsync.code.${target.label} — run the test through Gradle",
                    )
                val files = inputs.split(File.pathSeparator).filter { it.isNotBlank() }.map(::File)
                val classes = when (target) {
                    CodeTarget.JVM, CodeTarget.ANDROID -> BytecodeReader.read(files)
                    CodeTarget.IOS_ARM64, CodeTarget.IOS_SIMULATOR_ARM64 -> IrReader.read(files)
                }
                CodeBase(target, classes)
            }
        }
    }
}
